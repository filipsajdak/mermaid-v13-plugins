#!/usr/bin/env node
// @ts-check
/**
 * Generates `src/icons.ts` from v12's BPMN icon pack (`bpmnIcons.ts` of the bpmn-beta series,
 * #8166): each Iconify body becomes allow-listed SVG data, path data as absolute commands the
 * plugin replays through `SvgWriter.path()`. v13 renders no `<use>`, `<symbol>` or raw markup.
 *
 *   node scripts/gen-icons.mjs <path to bpmnIcons.ts> > src/icons.ts
 */
import { readFileSync } from 'node:fs';

const source = readFileSync(process.argv[2] ?? '', 'utf8');
/** Each `name: { body: '…' }` entry of the pack, read as text: the pack is data, never run. */
const pack = {
  icons: Object.fromEntries(
    [...source.matchAll(/(?:'([\w-]+)'|([\w-]+))\s*:\s*\{\s*body:\s*'([^']*)'/g)].map((m) => [
      m[1] ?? m[2] ?? '',
      { body: m[3] ?? '' },
    ]),
  ),
};

const ATTRS = [
  'fill',
  'stroke',
  'stroke-width',
  'stroke-linecap',
  'stroke-linejoin',
  'opacity',
  'class',
];
const NUMERIC = new Set(['stroke-width', 'opacity']);

/**
 * Path data as absolute M, L, C, A and Z commands.
 * @param {string} d
 * @returns {(string | number)[][]}
 */
function absolute(d) {
  const tokens = d.match(/[a-zA-Z]|-?(?:\d+\.?\d*|\.\d+)(?:e-?\d+)?/g) ?? [];
  /** @type {(string | number)[][]} */
  const out = [];
  let i = 0;
  let cmd = '';
  let x = 0;
  let y = 0;
  let sx = 0;
  let sy = 0;
  /** @type {[number, number] | null} */
  let lastC = null;
  const num = () => Number(tokens[i++]);
  const flag = () => {
    // Arc flags may be written without separators (`a5 5 0 0 1 5 5` or `0 01`).
    const t = tokens[i] ?? '0';
    if (t.length > 1 && /^[01]/.test(t)) {
      tokens[i] = t.slice(1);
      return Number(t[0]);
    }
    i++;
    return Number(t);
  };
  while (i < tokens.length) {
    if (/[a-zA-Z]/.test(tokens[i] ?? '')) cmd = tokens[i++] ?? '';
    const rel = cmd === cmd.toLowerCase();
    const ox = rel ? x : 0;
    const oy = rel ? y : 0;
    switch (cmd.toUpperCase()) {
      case 'M':
        x = ox + num();
        y = oy + num();
        sx = x;
        sy = y;
        out.push(['M', x, y]);
        cmd = rel ? 'l' : 'L';
        lastC = null;
        break;
      case 'L':
        x = ox + num();
        y = oy + num();
        out.push(['L', x, y]);
        lastC = null;
        break;
      case 'H':
        x = ox + num();
        out.push(['L', x, y]);
        lastC = null;
        break;
      case 'V':
        y = oy + num();
        out.push(['L', x, y]);
        lastC = null;
        break;
      case 'C': {
        const [x1, y1, x2, y2] = [ox + num(), oy + num(), ox + num(), oy + num()];
        x = ox + num();
        y = oy + num();
        out.push(['C', x1, y1, x2, y2, x, y]);
        lastC = [x2, y2];
        break;
      }
      case 'S': {
        const [x1, y1] = lastC ? [2 * x - lastC[0], 2 * y - lastC[1]] : [x, y];
        const [x2, y2] = [ox + num(), oy + num()];
        x = ox + num();
        y = oy + num();
        out.push(['C', x1, y1, x2, y2, x, y]);
        lastC = [x2, y2];
        break;
      }
      case 'A': {
        const rx = num();
        const ry = num();
        const rot = num();
        const large = flag();
        const sweep = flag();
        x = ox + num();
        y = oy + num();
        out.push(['A', rx, ry, rot, large, sweep, x, y]);
        lastC = null;
        break;
      }
      case 'Z':
        out.push(['Z']);
        x = sx;
        y = sy;
        lastC = null;
        break;
      default:
        throw new Error(`unsupported path command ${cmd} in ${d}`);
    }
  }
  return out.map((c) => c.map((v) => (typeof v === 'number' ? Math.round(v * 1000) / 1000 : v)));
}

/**
 * One `<path …/>` or `<circle …/>` of a body.
 * @param {string} tag
 * @param {string} attrText
 */
function element(tag, attrText) {
  /** @type {Record<string, string>} */
  const attrs = Object.fromEntries(
    [...attrText.matchAll(/([\w-]+)="([^"]*)"/g)].map((m) => [m[1] ?? '', m[2] ?? '']),
  );
  /** @type {Record<string, string | number>} */
  const kept = {};
  for (const name of ATTRS) {
    if (attrs[name] !== undefined)
      kept[name] = NUMERIC.has(name) ? Number(attrs[name]) : attrs[name];
  }
  if (tag === 'path') return { tag, d: absolute(attrs.d ?? ''), attrs: kept };
  return { tag, cx: Number(attrs.cx), cy: Number(attrs.cy), r: Number(attrs.r), attrs: kept };
}

/** @type {Record<string, unknown[]>} */
const icons = {};
for (const [name, { body }] of Object.entries(pack.icons)) {
  icons[name] = [...body.matchAll(/<(path|circle)\b([^>]*)\/>/g)].map((m) =>
    element(m[1] ?? '', m[2] ?? ''),
  );
}

process.stdout
  .write(`// Generated by scripts/gen-icons.mjs from v12's BPMN icon pack (the bpmn-beta series, #8166).
// Do not edit: change the generator or the pack and run it again.
import type { IconElement } from './icon-types.ts';

/** The pack's view box is 24 by 24. */
export const ICON_BOX = 24;

export const ICONS: Readonly<Record<string, readonly IconElement[]>> = ${JSON.stringify(icons, null, 2)};
`);
